  async function fetchFromSupabase() {
    var PAGE_SIZE = 1000;
    var all = [];
    var offset = 0;

    while (true) {
      var url = _SB_URL + '/rest/v1/dossier_snapshots?select=' + _COLUMNS + '&order=created_at.desc&limit=' + PAGE_SIZE + '&offset=' + offset;
      var res = await fetch(url, {
        headers: {
          'apikey': _SB_KEY,
          'Authorization': 'Bearer ' + _SB_KEY,
          'Prefer': 'count=exact'
        }
      });
      if (!res.ok) throw new Error('Erreur API: ' + res.status);
      var rows = await res.json();
      all = all.concat(rows);
      if (rows.length < PAGE_SIZE) break;
      offset += PAGE_SIZE;
    }

    return all;
  }

